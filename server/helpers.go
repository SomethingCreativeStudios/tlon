func (s *Service) links(ctxURL *url.URL, scope, catalogID string, search store.Search, first, last []any, hasPrev, hasNext bool, mediaType string) []api.Link {
	links := []api.Link{makeLink(s.publicURL, ctxURL, "self", "", mediaType)}
	if hasNext && len(last) > 0 {
		if token, err := s.cursors.Encode(catalogID, scope, search.Sort, store.CursorNext, last); err == nil {
			links = append(links, makeLink(s.publicURL, ctxURL, "next", token, mediaType))
		}
	}
	if hasPrev && len(first) > 0 {
		if token, err := s.cursors.Encode(catalogID, scope, search.Sort, store.CursorPrev, first); err == nil {
			links = append(links, makeLink(s.publicURL, ctxURL, "prev", token, mediaType))
		}
	}
	return links
}
func makeLink(publicURL string, current *url.URL, rel, token, mediaType string) api.Link {
	copy := *current
	query := copy.Query()
	if token != "" {
		query.Set("cursor", token)
	}
	copy.RawQuery = query.Encode()
	href := strings.TrimRight(publicURL, "/") + copy.EscapedPath()
	if copy.RawQuery != "" {
		href += "?" + copy.RawQuery
	}
	return api.Link{Href: href, Rel: rel, Type: &mediaType}
}
func expectedVersion(value *string) (*int64, error) {
	if value == nil {
		return nil, nil
	}
	if strings.TrimSpace(*value) == "*" {
		wildcard := int64(-1)
		return &wildcard, nil
	}
	version, err := etag.Parse(*value)
	if err != nil {
		return nil, err
	}
	return &version, nil
}
func location(publicURL, catalogID, recordID string) string {
	return strings.TrimRight(publicURL, "/") + "/collections/" + url.PathEscape(catalogID) + "/items/" + url.PathEscape(recordID)
}

func schemaProperties[T any](input map[string]T, facetDefinitions map[string]store.FacetDefinition) map[string]any {
	result := map[string]any{}
	faceted := map[string]bool{}
	for _, definition := range facetDefinitions {
		if definition.Property != "" {
			faceted[definition.Property] = true
		}
	}
	names := make([]string, 0, len(input))
	for name := range input {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		raw, _ := json.Marshal(input[name])
		var value map[string]any
		_ = json.Unmarshal(raw, &value)
		delete(value, "x-tlon-path")
		if faceted[name] {
			value["facet"] = true
		}
		result[name] = value
	}
	return result
}
