const catalogProfile = "http://www.opengis.net/def/profile/OGC/0/ogc-catalog"

func (s *Service) recordModel(stored store.StoredRecord) (api.Record, error) {
	var result api.Record
	err := json.Unmarshal(stored.Document, &result)
	return result, err
}

func (s *Service) catalogModel(value store.Catalog) (api.Catalog, error) {
	var doc map[string]any
	if err := json.Unmarshal(value.Bundle.Catalog, &doc); err != nil {
		return api.Catalog{}, err
	}
	base := s.publicURL + "/collections/" + url.PathEscape(value.ID)
	doc["supportsNonAutogeneratedResourceIds"] = true
	doc["defaultSortOrder"] = value.Bundle.DefaultSortOrder
	doc["conformsTo"] = []string{catalogProfile}
	doc["links"] = []any{
		map[string]any{"rel": "self", "type": "application/json", "href": base}, map[string]any{"rel": "items", "type": "application/geo+json", "href": base + "/items"}, map[string]any{"rel": "queryables", "type": "application/schema+json", "href": base + "/queryables"}, map[string]any{"rel": "sortables", "type": "application/schema+json", "href": base + "/sortables"}, map[string]any{"rel": "facets", "type": "application/facets+json", "href": base + "/facets"}, map[string]any{"rel": "describedby", "type": "application/schema+json", "href": base + "/schema"}, map[string]any{"rel": "profile", "type": "text/html", "href": catalogProfile}}
	raw, err := json.Marshal(doc)
	if err != nil {
		return api.Catalog{}, err
	}
	var result api.Catalog
	err = json.Unmarshal(raw, &result)
	return result, err
}

func parseSort(values *[]string) ([]store.SortField, error) {
	if values == nil {
		return nil, nil
	}
	result := make([]store.SortField, 0, len(*values))
	for _, value := range *values {
		value = strings.TrimSpace(value)
		if value == "" {
			return nil, fmt.Errorf("invalid empty sort field")
		}
		direction := "asc"
		if value[0] == '+' {
			value = value[1:]
		} else if value[0] == '-' {
			direction = "desc"
			value = value[1:]
		}
		if value == "" {
			return nil, fmt.Errorf("invalid empty sort field")
		}
		result = append(result, store.SortField{Property: value, Direction: direction})
	}
	return result, nil
}

func (s *Service) recordSearch(catalogValue store.Catalog, params api.SearchRecordsParams) (store.Search, string, error) {
	search := store.Search{Limit: s.defaultLimit}
	if params.Bbox != nil {
		for _, v := range *params.Bbox {
			search.Bbox = append(search.Bbox, float64(v))
		}
	}
	if params.Datetime != nil {
		search.Datetime = string(*params.Datetime)
	}
	if params.Q != nil {
		search.Q = []string(*params.Q)
	}
	if params.Type != nil {
		search.Types = []string(*params.Type)
	}
	if params.Ids != nil {
		search.IDs = []string(*params.Ids)
	}
	if params.ExternalIds != nil {
		search.ExternalIDs = []string(*params.ExternalIds)
	}
	if params.Limit != nil {
		search.Limit = int(*params.Limit)
	}
	if search.Limit < 0 || search.Limit > s.maximumLimit {
		return search, "", fmt.Errorf("limit must be between 0 and %d", s.maximumLimit)
	}
	var err error
	search.Sort, err = parseSort(params.Sortby)
	if err != nil {
		return search, "", err
	}
	search.Sort, err = catalog.NormalizeSort(search.Sort, catalogValue.Bundle.DefaultSortOrder, catalogValue.Bundle.Sortables)
	if err != nil {
		return search, "", err
	}
	if params.Filter != nil {
		search.Filter = string(*params.Filter)
	}
	if params.FilterLang != nil && string(*params.FilterLang) != "cql2-text" {
		return search, "", fmt.Errorf("filter-lang must be cql2-text")
	}
	if params.FacetsParameter != nil {
		value := string(*params.FacetsParameter)
		search.Facets = &value
	}
	scope, err := cursor.Scope(search)
	if err != nil {
		return search, "", err
	}
	if params.Cursor != nil {
		search.Position, err = s.cursors.Decode(string(*params.Cursor), catalogValue.ID, scope, search.Sort)
		if err != nil {
			return search, "", err
		}
	}
	return search, scope, nil
}

